import { fedExZoneMap } from "./expressZonesFedEx";

// 按渠道ID获取分区表
export function getZoneMap(carrierId: string): Record<string, string> {
  const id = carrierId.toLowerCase();
  if (id === "dhl") {
    // DHL 分区是数字，转为字符串统一处理
    const result: Record<string, string> = {};
    for (const [code, zone] of Object.entries(dhlZoneMap)) {
      result[code] = String(zone);
    }
    return result;
  }
  if (id === "fedex") return fedExZoneMap;
  // UPS 无分区，所有国家统一返回 "1"
  if (id === "ups") {
    return {};
  }
  return {};
}

// 根据国家代码获取分区号，找不到返回默认分区
export function getZone(carrierId: string, countryCode: string): string {
  const id = carrierId.toLowerCase();
  // UPS 无分区概念，所有国家默认分区 1
  if (id === "ups") return "1";
  const zoneMap = getZoneMap(carrierId);
  return zoneMap[countryCode] || "";
}

// 获取默认分区（用于找不到分区时）
export function getDefaultZone(carrierId: string): string {
  const id = carrierId.toLowerCase();
  if (id === "dhl") return "9";
  if (id === "fedex") return "2";
  if (id === "ups") return "1";
  return "";
}
